/// 참조가 일어난 자리가 선언의 인터페이스인지 본문인지.
///
/// 접근 수준 판정은 "이 참조가 다른 모듈에서도 보여야 하는가"를 물어야 하는데,
/// 인덱스의 참조에는 그 정보가 없다. 그래서 구문 분석이 참조 위치를 함수·접근자
/// 본문과 대조해 이 값을 채운다.
///
/// 보수 방향이 중요하다. 본문으로 잘못 분류하면 필요 없는 공개 노출을 요구하지
/// 않아 "internal 로 줄여도 된다"는 틀린 답이 나온다. 그래서 판단하지 못한
/// 참조는 인터페이스로 간주한다.
public enum ReferencePosition: String, Codable, Sendable, CaseIterable {
    /// 선언의 인터페이스 — 타입 표기, 상속 절, 제네릭 제약, 기본값 등.
    ///
    /// 이 자리의 참조는 감싸는 선언이 공개라면 대상도 공개여야 컴파일된다.
    case signature
    /// 함수·접근자 본문.
    ///
    /// 같은 모듈 안의 선언은 본문에서 자유롭게 쓸 수 있다 — 대상이 internal 이어도
    /// 감싸는 선언의 인터페이스는 바뀌지 않는다.
    case body
    /// 소스를 읽지 못해 판단하지 못했다. 보수적으로 인터페이스와 같이 다룬다.
    case unknown
}
