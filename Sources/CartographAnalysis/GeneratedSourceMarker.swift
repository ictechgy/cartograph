import CartographCore
import Foundation

/// 파일 앞의 일반 한 줄 주석에서 명시적 생성 마커만 읽는 제한된 어휘 검사다.
public enum GeneratedSourceMarker {
    /// 블록·문서 주석은 해석하지 않고, 코드 뒤나 문자열 속의 마커는 인정하지 않는다.
    public static func inspect(prefix: String, hasMoreBytes: Bool) -> GeneratedMarkerReview {
        let source = prefix.hasPrefix("\u{FEFF}") ? String(prefix.dropFirst()) : prefix
        let normalized = source.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        let lines = normalized.split(separator: "\n", omittingEmptySubsequences: false)
        for (offset, raw) in lines.enumerated() {
            if hasMoreBytes && offset == lines.count - 1 { return .init(status: .prefixLimit) }
            let line = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if line.isEmpty { continue }
            if line.hasPrefix("/*") || line.hasPrefix("///") || line.hasPrefix("//!") {
                return .init(status: .unsupportedHeader)
            }
            guard line.hasPrefix("//") else { return .init(status: .noMarkerInHeader) }
            guard line.utf8.count <= 512 else { return .init(status: .unsupportedHeader) }
            let text = line.dropFirst(2).trimmingCharacters(in: .whitespaces)
            if isMarker(text) {
                return .init(status: .markerObserved,
                    evidence: .init(line: offset + 1, text: line))
            }
        }
        return .init(status: hasMoreBytes ? .prefixLimit : .noMarkerInHeader)
    }

    private static func isMarker(_ text: String) -> Bool {
        if text == "@generated" || text.hasPrefix("@generated ") { return true }
        let prefixes = ["Generated by ", "Generated using ", "This file was generated by ",
                        "This file is generated by "]
        return prefixes.contains { prefix in
            guard text.hasPrefix(prefix) else { return false }
            let generator = text.dropFirst(prefix.count).trimmingCharacters(in: .whitespaces)
            guard !generator.isEmpty else { return false }
            guard let word = generator.split(whereSeparator: { !$0.isLetter }).first?.lowercased() else { return false }
            return word != "hand" && word != "human" && word != "humans"
        }
    }
}
