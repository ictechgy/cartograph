import CartographCore
import CartographKit
import CartographTestSupport
import Foundation
import Testing

@Suite("선택적 생성 헤더 검토의 IO와 진단 보존")
struct GeneratedSourceReviewTests {
    @Test("기본 API는 파일을 읽지 않고 마커 없는 파일의 요약도 보존한다")
    func defaultMakesNoFileAccess() throws {
        let fs = HeaderReadRecorder(files: ["/p/Generated.swift": "// @generated\n"])
        let diagnostics = [finding("Generated.swift"), finding("Tokens.swift")]
        let result = try service(fs).findingReviewDocument(diagnostics: diagnostics)
        #expect(result.diagnostics == diagnostics)
        #expect(result.files.map(\.path) == ["Generated.swift", "Tokens.swift"])
        #expect(result.files.allSatisfy { $0.generatedMarker == nil })
        #expect(fs.reads.isEmpty && fs.unboundedReads == 0 && fs.resolutions == 0)
        #expect(!result.markerReviewRequested)
    }

    @Test("마커 제안을 더해도 생성 코드와 수동 토큰의 모든 원래 진단이 남는다")
    func markerAndHumanManagedFile() throws {
        let fs = HeaderReadRecorder(files: [
            "/p/Generated.swift": "// Generated by FixtureTool\nfunc unused() {}",
            "/p/DesignTokens.swift": "// Human-managed design tokens\nlet unusedToken = 1",
            "/p/NeedleGenerated.swift": "// Copyright\nimport Foundation\nfunc unusedProvider() {}"
        ])
        let diagnostics = [finding("Generated.swift"), finding("DesignTokens.swift"), finding("NeedleGenerated.swift")]
        let result = try service(fs).findingReviewDocument(diagnostics: diagnostics,
            options: .init(inspectGeneratedHeaders: true))
        #expect(result.diagnostics == diagnostics)
        #expect(result.findingCount == 3)
        let generated = try #require(result.files.first { $0.path == "Generated.swift" }?.generatedMarker)
        #expect(generated.status == .markerObserved)
        #expect(generated.evidence?.text == "// Generated by FixtureTool")
        #expect(generated.fileStableDuringRead == nil)
        for path in ["DesignTokens.swift", "NeedleGenerated.swift"] {
            let review = try #require(result.files.first { $0.path == path }?.generatedMarker)
            #expect(review.status == .noMarkerInHeader)
            #expect(review.suggestion == nil)
        }
        #expect(fs.unboundedReads == 0)
        #expect(result.limitations.contains { $0.contains("not proof of generator execution") })
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let data = try encoder.encode(result)
        #expect(try JSONDecoder().decode(FindingReviewDocument.self, from: data) == result)
        let json = try #require(JSONSerialization.jsonObject(with: data) as? [String: Any])
        #expect(json["findingCount"] as? Int == 3)
        #expect(json["omittedFileCount"] as? Int == 0)
        #expect(try encoder.encode(result) == data)
    }

    @Test("전체 읽기 예산은 lookahead를 포함하고 다음 파일을 읽지 않는다")
    func readBudgetAndPrefixLimit() throws {
        let fs = HeaderReadRecorder(files: [
            "/p/A.swift": String(repeating: " ", count: 10_000), "/p/B.swift": "// @generated\n"
        ])
        let result = try service(fs).findingReviewDocument(diagnostics: [finding("A.swift"), finding("B.swift")],
            options: .init(inspectGeneratedHeaders: true, maximumPrefixBytes: 64, maximumTotalBytes: 65))
        #expect(fs.reads == [.init(path: "/p/A.swift", maximum: 64, returned: 65)])
        #expect(fs.unboundedReads == 0)
        #expect(result.markerBytesRead == 65 && result.markerReadBudgetConsumed == 65)
        #expect(result.files.map { $0.generatedMarker?.status } == [.prefixLimit, .byteBudget])
        #expect(result.diagnostics.count == 2)
    }

    @Test("파일 예산과 요약 상한을 별도로 남기고 잘린 파일을 안전하다고 하지 않는다")
    func independentFileBudgets() throws {
        let fs = HeaderReadRecorder(files: ["/p/A.swift": "// @generated\n", "/p/B.swift": "// @generated\n"])
        let result = try service(fs).findingReviewDocument(
            diagnostics: [finding("C.swift"), finding("B.swift"), finding("A.swift")],
            options: .init(maximumFiles: 2, inspectGeneratedHeaders: true, maximumMarkerFiles: 1))
        #expect(result.omittedFileCount == 1 && result.findingCount == 3)
        #expect(result.files.map { $0.generatedMarker?.status } == [.markerObserved, .fileBudget])
        #expect(fs.reads.count == 1)
    }

    @Test("밖의 경로와 링크는 읽지 않고 잘못된 UTF8과 읽기 오류를 구분한다")
    func unreadableAndOutsideProject() throws {
        let fs = HeaderReadRecorder(files: ["/outside.swift": "// @generated\n", "/p/A.swift": ""])
        fs.aliases["/p/Link.swift"] = "/outside.swift"
        try fs.base.write(Data([0xff]), to: "/p/A.swift")
        let result = try service(fs).findingReviewDocument(
            diagnostics: [finding("../outside.swift"), finding("Link.swift"), finding("A.swift"), finding("Missing.swift")],
            options: .init(inspectGeneratedHeaders: true))
        let statuses = Dictionary(uniqueKeysWithValues: result.files.map {
            ($0.path, $0.generatedMarker?.status ?? .unreadable)
        })
        #expect(statuses["../outside.swift"] == .outsideProject)
        #expect(statuses["Link.swift"] == .outsideProject)
        #expect(statuses["A.swift"] == .invalidUTF8)
        #expect(statuses["Missing.swift"] == .unreadable)
        #expect(fs.reads.allSatisfy { $0.path.hasPrefix("/p/") })
        #expect(result.files.allSatisfy { $0.generatedMarker?.suggestion == nil })
    }

    @Test("실패한 읽기는 예약 예산을 소비하지만 관측 바이트를 꾸며내지 않는다")
    func failedReadUsesReservation() throws {
        let fs = HeaderReadRecorder(files: [:])
        let result = try service(fs).findingReviewDocument(diagnostics: [finding("A.swift"), finding("B.swift")],
            options: .init(inspectGeneratedHeaders: true, maximumPrefixBytes: 64, maximumTotalBytes: 65))
        #expect(result.markerBytesRead == 0)
        #expect(result.markerReadBudgetConsumed == 65)
        #expect(result.files.map { $0.generatedMarker?.status } == [.unreadable, .byteBudget])
    }

    @Test("읽는 사이 파일이 바뀌면 관측 마커를 제안하지 않는다")
    func changedHeaderIsUnknown() throws {
        let fs = HeaderReadRecorder(files: ["/p/A.swift": "// @generated\n"])
        fs.provideStamps = true
        fs.changeAfterRead = true
        let result = try service(fs).findingReviewDocument(diagnostics: [finding("A.swift")],
            options: .init(inspectGeneratedHeaders: true))
        #expect(result.files.first?.generatedMarker?.status == .changedDuringRead)
        #expect(result.files.first?.generatedMarker?.evidence == nil)
        #expect(result.files.first?.generatedMarker?.fileStableDuringRead == false)
        fs.changeAfterRead = false
        let stable = try service(fs).findingReviewDocument(diagnostics: [finding("A.swift")],
            options: .init(inspectGeneratedHeaders: true))
        #expect(stable.files.first?.generatedMarker?.fileStableDuringRead == true)
    }

    @Test("비정상 예산은 IO 전에 거부한다")
    func invalidBudgets() throws {
        let fs = HeaderReadRecorder(files: [:])
        let invalid: [FindingReviewOptions] = [
            .init(maximumFiles: 0), .init(maximumMarkerFiles: 0), .init(maximumMarkerFiles: 2001),
            .init(maximumPrefixBytes: 63), .init(maximumPrefixBytes: 65_537),
            .init(maximumTotalBytes: 64), .init(maximumTotalBytes: 16_777_217)
        ]
        for options in invalid {
            #expect(throws: CartographError.self) {
                try service(fs).findingReviewDocument(diagnostics: [finding("A.swift")], options: options)
            }
        }
        #expect(fs.reads.isEmpty && fs.resolutions == 0)
    }

    private func service(_ fileSystem: any FileSystem) -> CartographService {
        .init(configuration: .init(projectPath: "/p"), environment: .init(fileSystem: fileSystem))
    }

    private func finding(_ path: String) -> Diagnostic {
        .init(ruleIdentifier: "unused-symbol", severity: .warning, message: path,
            location: .init(path: path, line: 2, column: 1), subject: path)
    }
}

private final class HeaderReadRecorder: FileSystem, @unchecked Sendable {
    struct Read: Equatable { let path: String; let maximum: Int; let returned: Int }
    let base: InMemoryFileSystem
    var aliases: [String: String] = [:]
    var provideStamps = false
    var changeAfterRead = false
    private let lock = NSLock()
    private var recorded: [Read] = []
    private var unbounded = 0
    private var resolved = 0
    var reads: [Read] { lock.withLock { recorded } }
    var unboundedReads: Int { lock.withLock { unbounded } }
    var resolutions: Int { lock.withLock { resolved } }
    var currentDirectoryPath: String { "/p" }

    init(files: [String: String]) { base = .init(currentDirectoryPath: "/p", files: files) }
    func realPath(at path: String) throws -> String {
        lock.withLock { resolved += 1 }
        return aliases[path] ?? (path as NSString).standardizingPath
    }
    func readData(at path: String) throws -> Data {
        lock.withLock { unbounded += 1 }
        return try base.readData(at: path)
    }
    func readData(at path: String, maximumBytes: Int) throws -> Data {
        let data = try base.readData(at: path).prefix(maximumBytes + 1)
        lock.withLock { recorded.append(.init(path: path, maximum: maximumBytes, returned: data.count)) }
        return data
    }
    func fingerprintStamp(at path: String) -> FileFingerprintStamp? {
        guard provideStamps else { return nil }
        return .init(resolvedPath: path, device: 1, inode: 1, size: 1, modificationSeconds: 1,
            modificationNanoseconds: 0, changeSeconds: changeAfterRead && !reads.isEmpty ? 2 : 1,
            changeNanoseconds: 0, mode: 0o100644)
    }
    func fileExists(at path: String) -> Bool { base.fileExists(at: path) }
    func directoryExists(at path: String) -> Bool { base.directoryExists(at: path) }
    func contentsOfDirectory(at path: String) throws -> [String] { try base.contentsOfDirectory(at: path) }
    func write(_ data: Data, to path: String) throws { try base.write(data, to: path) }
}
